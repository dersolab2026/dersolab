/**
 * Verilen metin veya konudan belirli bir film araması varsa eşleşen filmi bulur
 */
export function findMatchingCuratedMovie(text: string): CuratedMovieRecommendation | null {
  if (!text) return null
  const lower = text
    .toLocaleLowerCase('tr-TR')
    .replace(/['".,!?()-]/g, ' ')
    .replace(/\s+/g, ' ')
    .trim()

  for (const movie of CURATED_MOVIE_RECOMMENDATIONS) {
    for (const kw of movie.keywords) {
      if (lower.includes(kw)) {
        return movie
      }
    }
    const titleLower = movie.title.toLocaleLowerCase('tr-TR')
    const origLower = movie.originalTitle.toLowerCase()
    if (lower.includes(titleLower) || lower.includes(origLower)) {
      return movie
    }
  }
  return null
}

/**
 * Ortaokul ve Lise için eşleşmiş 2'li film önerisi çifti seçer
 */
export function pickCuratedMoviePair(
  excludeText?: string,
  variationSeed: number = 1,
  specificPrompt?: string
): { ortaokul: CuratedMovieRecommendation; lise: CuratedMovieRecommendation } {
  const ortList = CURATED_MOVIE_RECOMMENDATIONS.filter((m) => m.level === 'ortaokul')
  const lisList = CURATED_MOVIE_RECOMMENDATIONS.filter((m) => m.level === 'lise')
  const excludeLower = (excludeText || '').toLocaleLowerCase('tr-TR')

  const matchedSpecific = specificPrompt ? findMatchingCuratedMovie(specificPrompt) : null

  const availOrt = ortList.filter((m) => !excludeLower.includes(m.title.toLocaleLowerCase('tr-TR')))
  const availLis = lisList.filter((m) => !excludeLower.includes(m.title.toLocaleLowerCase('tr-TR')))

  const poolOrt = availOrt.length > 0 ? availOrt : ortList
  const poolLis = availLis.length > 0 ? availLis : lisList

  const idxOrt = Math.abs(variationSeed - 1) % poolOrt.length
  const idxLis = Math.abs(variationSeed - 1) % poolLis.length

  const chosenOrt = matchedSpecific?.level === 'ortaokul' ? matchedSpecific : poolOrt[idxOrt]
  const chosenLis = matchedSpecific?.level === 'lise' ? matchedSpecific : poolLis[idxLis]

  return {
    ortaokul: chosenOrt,
    lise: chosenLis,
  }
}

